export function replaceLegacyEnglishContractTemplate(
  template: ContractTemplate,
) {
  const combinedText = [
    template.paymentTerms,
    template.warrantyTerms,
    template.executionTerms,
    template.contractTerms,
    template.firstPartyObligations,
    template.secondPartyObligations,
  ].join(" ");
  const hasLegacyEnglishDefaults =
    combinedText.includes("advance payment") ||
    combinedText.includes("Alumex provides warranty") ||
    combinedText.includes("Execution starts after") ||
    combinedText.includes("The First Party shall") ||
    combinedText.includes("The Second Party shall") ||
    combinedText.includes("approved shop drawings");

  return hasLegacyEnglishDefaults ? arabicContractTemplateDefaults : template;
}
