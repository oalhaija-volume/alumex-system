-- Run only against a disposable database after all repository migrations.
begin;
do $$
declare
 indoor uuid:=gen_random_uuid(); manager uuid:=gen_random_uuid(); outdoor uuid:=gen_random_uuid(); other_branch uuid:=gen_random_uuid();
 site uuid:=gen_random_uuid(); other_site uuid:=gen_random_uuid(); saved_id uuid:=gen_random_uuid(); new_id uuid:=gen_random_uuid(); foreign_id uuid:=gen_random_uuid();
 residential_site uuid:=gen_random_uuid(); residential_opening uuid:=gen_random_uuid(); closed_site uuid:=gen_random_uuid();
 late_site uuid:=gen_random_uuid(); late_saved uuid:=gen_random_uuid(); late_new uuid:=gen_random_uuid(); late_facade jsonb; late_quote jsonb; late_flow public.sales_workflows;
 flow public.sales_workflows; quote jsonb; proposed jsonb; original_facade jsonb; new_facade jsonb; foreign_facade jsonb; third_facade jsonb;
 invalid record; bad jsonb; batch jsonb; old_quote jsonb;
begin
 -- Older facade IDs need not have been generated by the current v4-only editor.
 saved_id=overlay(saved_id::text placing '1' from 15 for 1)::uuid;
 insert into auth.users(id,email) values
  (indoor,indoor::text||'@example.invalid'),(manager,manager::text||'@example.invalid'),
  (outdoor,outdoor::text||'@example.invalid'),(other_branch,other_branch::text||'@example.invalid');
 update profiles set role='Indoor Sales',branch='Karkh',is_active=true,status='Active' where id=indoor;
 update profiles set role='Sales Manager',branch='Karkh',is_active=true,status='Active' where id=manager;
 update profiles set role='Outdoor Sales',is_active=true,status='Active' where id=outdoor;
 update profiles set role='Indoor Sales',branch='Rasafa',is_active=true,status='Active' where id=other_branch;
 perform sync_field_change(gen_random_uuid(),indoor,site,'register',jsonb_build_object(
  'client',jsonb_build_object('clientName','Quotation facade addition test','clientType','individual','mobile','00000000000'),
  'project',jsonb_build_object('address','Baghdad','structureReadiness','ready','buildingType','commercial_building','locationLatitude',33.3,'locationLongitude',44.4,'assignedOutdoorSalesId',indoor)),now(),null);
 perform sync_field_change(gen_random_uuid(),indoor,other_site,'register',jsonb_build_object(
  'client',jsonb_build_object('clientName','Other facade addition test','clientType','individual','mobile','00000000001'),
  'project',jsonb_build_object('address','Baghdad','structureReadiness','ready','buildingType','commercial_building','locationLatitude',33.31,'locationLongitude',44.41,'assignedOutdoorSalesId',indoor)),now(),null);
 perform sync_field_change(gen_random_uuid(),indoor,site,'opening',jsonb_build_object(
  'id',saved_id,'floor','Whole building','room','Other','otherRoom','Facade 1','width',1650,'height',380,'quantity',1,
  'structuralType','Facade','openingType',null,'workArea','facade','facadeNumber',1),now(),null);
 perform sync_field_change(gen_random_uuid(),indoor,other_site,'opening',jsonb_build_object(
  'id',foreign_id,'floor','Whole building','room','Other','otherRoom','Facade 2','width',500,'height',500,'quantity',1,
  'structuralType','Facade','openingType',null,'workArea','facade','facadeNumber',2),now(),null);
 perform sync_field_change(gen_random_uuid(),indoor,site,'finish','{}',now(),null);
 select jsonb_build_object('id',id,'floor',floor,'room',room,'width',width,'height',height,'quantity',quantity,
  'opening_type',opening_type,'opening_direction',opening_direction,'has_arch',has_arch,'has_roller_shutter',has_roller_shutter,
  'work_area',work_area,'facade_number',facade_number) into original_facade from openings where id=saved_id;
 select jsonb_build_object('id',id,'floor',floor,'room',room,'width',width,'height',height,'quantity',quantity,
  'opening_type',opening_type,'opening_direction',opening_direction,'has_arch',has_arch,'has_roller_shutter',has_roller_shutter,
  'work_area',work_area,'facade_number',facade_number) into foreign_facade from openings where id=foreign_id;
 quote=jsonb_build_object('lines','[]'::jsonb,'additionalItems',jsonb_build_array(jsonb_build_object(
  'id','facade-service','name','Cladding','unit','sqm','rate',100000,'quantity',1,'total',100000)),
  'facadeMeasurements',jsonb_build_array(original_facade),'total',100000,'currency','IQD');
 flow=advance_sales_flow(site,'save',0,jsonb_set(quote,'{facadeMeasurements}',jsonb_build_array(
  original_facade-array['floor','room','quantity','opening_direction','has_arch','has_roller_shutter','work_area'])),indoor);
 old_quote=flow.quotation;
 new_facade=original_facade||jsonb_build_object('id',new_id,'room','Facade 2','facade_number',2,'height',390);
 proposed=quote||jsonb_build_object('facadeMeasurements',jsonb_build_array(original_facade,new_facade));

 -- Preserve the actor, branch and optimistic revision guards added after facades.
 begin
  perform advance_sales_flow(site,'save',flow.revision,proposed,outdoor);
  raise exception using errcode='ZX001',message='Outdoor facade quotation edit accepted';
 exception when insufficient_privilege then null; end;
 begin
  perform advance_sales_flow(site,'save',flow.revision,proposed,other_branch);
  raise exception using errcode='ZX001',message='Other branch facade quotation edit accepted';
 exception when insufficient_privilege then null; end;
 begin
  perform advance_sales_flow(site,'save',0,proposed,indoor);
  raise exception using errcode='ZX001',message='Stale facade quotation revision accepted';
 exception when sqlstate 'P0001' then assert sqlerrm='This project changed. Reload before continuing.'; end;

 for invalid in select * from (values
  ('malformed array',quote||'{"facadeMeasurements":{}}'::jsonb,'Facade dimensions changed. Reload the quotation.'),
  ('null array',quote||'{"facadeMeasurements":null}'::jsonb,'Facade dimensions changed. Reload the quotation.'),
  ('invalid UUID',quote||jsonb_build_object('facadeMeasurements',jsonb_build_array(original_facade,new_facade||'{"id":"invalid"}'::jsonb)),'Facade dimensions changed. Reload the quotation.'),
  ('new non-v4 UUID',quote||jsonb_build_object('facadeMeasurements',jsonb_build_array(original_facade,new_facade||'{"id":"11111111-1111-1111-8111-111111111111"}'::jsonb)),'Facade dimensions changed. Reload the quotation.'),
  ('missing original',quote||jsonb_build_object('facadeMeasurements',jsonb_build_array(new_facade)),'Facade dimensions changed. Reload the quotation.'),
  ('changed original',quote||jsonb_build_object('facadeMeasurements',jsonb_build_array(original_facade||'{"width":1}'::jsonb,new_facade)),'Facade dimensions changed. Reload the quotation.'),
  ('foreign project ID',quote||jsonb_build_object('facadeMeasurements',jsonb_build_array(original_facade,foreign_facade)),'Facade dimensions changed. Reload the quotation.'),
  ('duplicate ID',quote||jsonb_build_object('facadeMeasurements',jsonb_build_array(original_facade,new_facade,new_facade)),'Duplicate opening'),
  ('duplicate number',quote||jsonb_build_object('facadeMeasurements',jsonb_build_array(original_facade,new_facade||'{"facade_number":1,"room":"Facade 1"}'::jsonb)),'This facade number is already saved. Edit it or choose another number.'),
  ('repeated facade',quote||jsonb_build_object('facadeMeasurements',jsonb_build_array(original_facade,new_facade||'{"quantity":2}'::jsonb)),'Facade dimensions changed. Reload the quotation.'),
  ('wrong work area',quote||jsonb_build_object('facadeMeasurements',jsonb_build_array(original_facade,new_facade||'{"work_area":"internal"}'::jsonb)),'Facade dimensions changed. Reload the quotation.'),
  ('movement on facade',quote||jsonb_build_object('facadeMeasurements',jsonb_build_array(original_facade,new_facade||'{"opening_direction":"Sliding"}'::jsonb)),'Facade dimensions changed. Reload the quotation.'),
  ('arch on facade',quote||jsonb_build_object('facadeMeasurements',jsonb_build_array(original_facade,new_facade||'{"has_arch":true}'::jsonb)),'Facade dimensions changed. Reload the quotation.'),
  ('zero width',quote||jsonb_build_object('facadeMeasurements',jsonb_build_array(original_facade,new_facade||'{"width":0}'::jsonb)),'Facade dimensions changed. Reload the quotation.'),
  ('string dimension',quote||jsonb_build_object('facadeMeasurements',jsonb_build_array(original_facade,new_facade||'{"height":"390"}'::jsonb)),'Facade dimensions changed. Reload the quotation.'),
  ('excess precision',quote||jsonb_build_object('facadeMeasurements',jsonb_build_array(original_facade,new_facade||'{"width":1650.1234}'::jsonb)),'Enter a facade number and valid width and length.'),
  ('fractional number',quote||jsonb_build_object('facadeMeasurements',jsonb_build_array(original_facade,new_facade||'{"facade_number":2.5}'::jsonb)),'Facade dimensions changed. Reload the quotation.'),
  ('oversize number',quote||jsonb_build_object('facadeMeasurements',jsonb_build_array(original_facade,new_facade||'{"facade_number":1001}'::jsonb)),'Facade dimensions changed. Reload the quotation.'),
  ('wrong room',quote||jsonb_build_object('facadeMeasurements',jsonb_build_array(original_facade,new_facade||'{"room":"Office"}'::jsonb)),'Facade dimensions changed. Reload the quotation.')
 ) as cases(name,payload,message) loop
  begin
   perform advance_sales_flow(site,'save',flow.revision,invalid.payload,indoor);
   raise exception using errcode='ZX001',message='Invalid facade quotation accepted: '||invalid.name;
  exception when sqlstate 'P0001' then assert sqlerrm=invalid.message, invalid.name||': '||sqlerrm; end;
  assert (select count(*)=1 from openings where project_id=site), 'Rejected addition changed measurements';
  assert (select quotation=old_quote and revision=1 from sales_workflows where project_id=site), 'Rejected addition changed the saved quotation';
  assert not exists(select 1 from quotation_revisions where project_id=site), 'Rejected addition archived the saved quotation';
 end loop;

 perform sync_field_change(gen_random_uuid(),indoor,residential_site,'register',jsonb_build_object(
  'client',jsonb_build_object('clientName','Residential facade rejection test','clientType','individual','mobile','00000000002'),
  'project',jsonb_build_object('address','Baghdad','structureReadiness','ready','buildingType','villa_house','locationLatitude',33.32,'locationLongitude',44.42,'assignedOutdoorSalesId',indoor)),now(),null);
 perform sync_field_change(gen_random_uuid(),indoor,residential_site,'opening',jsonb_build_object(
  'id',residential_opening,'floor','GF','room','Office','width',100,'height',100,'quantity',1,'structuralType','Window','openingType','Sliding'),now(),null);
 perform sync_field_change(gen_random_uuid(),indoor,residential_site,'finish','{}',now(),null);
 bad=quote||jsonb_build_object('facadeMeasurements',jsonb_build_array(new_facade),
  'lines',jsonb_build_array(jsonb_build_object('opening',jsonb_build_object('id',residential_opening,'floor','GF','room','Office',
   'width',100,'height',100,'quantity',1,'opening_type','Window','opening_direction','Sliding'))));
 begin
  perform advance_sales_flow(residential_site,'save',0,bad,indoor);
  raise exception using errcode='ZX001',message='Facade added to a noncommercial project';
 exception when sqlstate 'P0001' then assert sqlerrm='Facade and Internal works are only available for commercial buildings.'; end;
 assert not exists(select 1 from sales_workflows where project_id=residential_site);
 assert (select count(*)=1 from openings where project_id=residential_site);
 perform sync_field_change(gen_random_uuid(),indoor,closed_site,'register',jsonb_build_object(
  'client',jsonb_build_object('clientName','Closed facade rejection test','clientType','individual','mobile','00000000003'),
  'project',jsonb_build_object('address','Baghdad','structureReadiness','ready','buildingType','commercial_building','locationLatitude',33.33,'locationLongitude',44.43,'assignedOutdoorSalesId',indoor)),now(),null);
 update projects set sales_status='closed' where id=closed_site;
 begin
  perform advance_sales_flow(closed_site,'save',0,proposed,indoor);
  raise exception using errcode='ZX001',message='Facade added to a closed project';
 exception when sqlstate 'P0001' then assert sqlerrm='This project is closed. Its quotation and contract history is read-only.'; end;

 -- Force a constraint failure after the workflow/history have been written.
 -- The entire revision must roll back when its new facade cannot be inserted.
 perform sync_field_change(gen_random_uuid(),indoor,late_site,'register',jsonb_build_object(
  'client',jsonb_build_object('clientName','Atomic facade rollback test','clientType','individual','mobile','00000000004'),
  'project',jsonb_build_object('address','Baghdad','structureReadiness','ready','buildingType','commercial_building','locationLatitude',33.34,'locationLongitude',44.44,'assignedOutdoorSalesId',indoor)),now(),null);
 perform sync_field_change(gen_random_uuid(),indoor,late_site,'opening',jsonb_build_object(
  'id',late_saved,'floor','Whole building','room','Other','otherRoom','Facade 1','width',100,'height',100,'quantity',1,
  'structuralType','Facade','openingType',null,'workArea','facade','facadeNumber',1),now(),null);
 update openings set opening_code='OP-'||late_new::text where id=late_saved;
 perform sync_field_change(gen_random_uuid(),indoor,late_site,'finish','{}',now(),null);
 late_facade=original_facade||jsonb_build_object('id',late_saved,'width',100,'height',100);
 late_quote=quote||jsonb_build_object('facadeMeasurements',jsonb_build_array(late_facade));
 late_flow=advance_sales_flow(late_site,'save',0,late_quote,indoor);
 late_quote=late_flow.quotation;
 begin
  perform advance_sales_flow(late_site,'save',1,late_quote||jsonb_build_object('facadeMeasurements',jsonb_build_array(late_facade,new_facade||jsonb_build_object('id',late_new))),indoor);
  raise exception using errcode='ZX001',message='Late facade insert failure was not propagated';
 exception when unique_violation then null; end;
 assert (select revision=1 and quotation=late_quote from sales_workflows where project_id=late_site);
 assert (select count(*)=1 from openings where project_id=late_site);
 assert not exists(select 1 from quotation_revisions where project_id=late_site);

 -- A new ID cannot be both a priced opening and an unpriced facade measurement.
 bad=proposed||jsonb_build_object('lines',jsonb_build_array(jsonb_build_object('opening',jsonb_build_object(
  'id',new_id,'floor','GF','room','Office','width',100,'height',100,'quantity',1,'opening_type','Window','opening_direction','Sliding'))));
 begin
  perform advance_sales_flow(site,'save',flow.revision,bad,indoor);
  raise exception using errcode='ZX001',message='ID shared by facade and priced opening accepted';
 exception when sqlstate 'P0001' then assert sqlerrm='Duplicate opening'; end;

 select jsonb_agg(new_facade||jsonb_build_object('id',gen_random_uuid(),'facade_number',number,'room','Facade '||number))
 into batch from generate_series(2,102) number;
 begin
  perform advance_sales_flow(site,'save',flow.revision,quote||jsonb_build_object('facadeMeasurements',jsonb_build_array(original_facade)||batch),indoor);
  raise exception using errcode='ZX001',message='More than 100 new facades accepted';
 exception when sqlstate 'P0001' then assert sqlerrm='Add up to 100 openings per revision.'; end;

 select jsonb_agg(jsonb_build_object('opening',jsonb_build_object('id',gen_random_uuid(),'floor','GF','room','Office',
  'width',100,'height',100,'quantity',1,'opening_type','Window','opening_direction','Sliding'))) into batch from generate_series(1,100);
 begin
  perform advance_sales_flow(site,'save',flow.revision,proposed||jsonb_build_object('lines',batch),indoor);
  raise exception using errcode='ZX001',message='Shared opening/facade addition limit was bypassed';
 exception when sqlstate 'P0001' then assert sqlerrm='Add up to 100 openings per revision.'; end;

 -- Sales Manager retains the same permission as Indoor Sales without losing attribution.
 flow=advance_sales_flow(site,'save',flow.revision,proposed,manager);
 assert flow.revision=2 and flow.quotation->>'version'='2' and flow.quotation->>'preparedBy'=manager::text;
 assert jsonb_array_length(flow.quotation->'facadeMeasurements')=2;
 assert (select count(*)=2 from openings where project_id=site);
 assert (select width=1650 and height=380 and facade_number=1 from openings where id=saved_id);
 assert (select width=1650 and height=390 and facade_number=2 and created_by=manager and quantity=1
  and opening_type='Facade' and work_area='facade' and floor='Whole building' and room='Facade 2'
  and opening_direction is null and has_arch=false and has_roller_shutter=false from openings where id=new_id);
 assert (select quotation=old_quote from quotation_revisions where project_id=site and version=1);

 -- Reloading/saving the same draft never duplicates an already committed facade.
 flow=advance_sales_flow(site,'save',flow.revision,flow.quotation,indoor);
 assert flow.revision=3 and (select count(*)=2 from openings where project_id=site);
 begin
  insert into openings(id,project_id,opening_code,floor,room,width,height,quantity,opening_type,opening_direction,site_readiness,created_by,work_area,facade_number)
  values(gen_random_uuid(),site,'UNQUOTED-FACADE','Whole building','Facade 3',100,100,1,'Facade',null,'ready',indoor,'facade',3);
  raise exception using errcode='ZX001',message='Unquoted facade inserted directly after quotation creation';
 exception when sqlstate 'P0001' then assert sqlerrm='Add new openings through a quotation revision'; end;
 begin
  update openings set width=width+1 where id=saved_id;
  raise exception using errcode='ZX001',message='Saved facade measurement changed after quotation creation';
 exception when sqlstate 'P0001' then null; end;

 -- Revising an unsigned contract preserves its old snapshot and clears approval.
 flow=advance_sales_flow(site,'approve',flow.revision,'{}',indoor);
 flow=advance_sales_flow(site,'contract',flow.revision,'{"number":"TEST-FACADE-ADDITIONS"}',indoor);
 third_facade=new_facade||jsonb_build_object('id',gen_random_uuid(),'facade_number',3,'room','Facade 3');
 proposed=flow.quotation||jsonb_build_object('facadeMeasurements',jsonb_build_array(original_facade,new_facade,third_facade));
 flow=advance_sales_flow(site,'save',flow.revision,proposed,indoor);
 assert flow.stage='quotation' and flow.approved_at is null and flow.contract is null;
 assert (select count(*)=3 from openings where project_id=site);
 assert exists(select 1 from quotation_revisions where project_id=site and previous_stage='contract'
  and jsonb_array_length(contract#>'{quotation,facadeMeasurements}')=2);
 flow=advance_sales_flow(site,'approve',flow.revision,'{}',indoor);
 flow=advance_sales_flow(site,'contract',flow.revision,'{"number":"TEST-FACADE-ADDITIONS-REVISED"}',indoor);
 assert jsonb_array_length(flow.contract#>'{quotation,facadeMeasurements}')=3;
 flow=advance_sales_flow(site,'sign',flow.revision,'{"method":"digital","signer":"Fixture client","signature":"fixture"}',indoor);
 begin
  perform advance_sales_flow(site,'save',flow.revision,proposed,indoor);
  raise exception using errcode='ZX001',message='Signed facade quotation revised';
 exception when sqlstate 'P0001' then assert sqlerrm='Signed contracts cannot be changed.'; end;
 assert not has_function_privilege('authenticated','public.advance_sales_flow(uuid,text,integer,jsonb,uuid)','EXECUTE');
 raise notice 'PASS: facade additions persist atomically with quotation revisions; original/foreign IDs, numbering, fields, cap, roles, branches, replay, unsigned/signed contracts and insertion locks are preserved';
end;
$$;
rollback;
