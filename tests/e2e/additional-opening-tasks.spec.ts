import { expect, test } from '@playwright/test';
import { savedFieldState } from './helpers/fieldState';
import type { FieldChange, FieldState } from '../../src/lib/offline/types';
test.use({ serviceWorkers: 'block' });
for (const locale of ['en','ar']) for (const quoted of [false,true]) test(`${locale}: CRM requests additional openings ${quoted?'after':'before'} quotation and Outdoor submits without replacing measurements`,async({page})=>{
 const indoor={id:'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa',name:'Indoor employee',role:'Indoor Sales',branch:'Karkh' as const};
 const outdoor={id:'bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb',name:'Outdoor employee',role:'Outdoor Sales'};
 const projectId='cccccccc-cccc-4ccc-8ccc-cccccccccccc';
 const original={id:'dddddddd-dddd-4ddd-8ddd-dddddddddddd',projectId,floor:'GF',room:'Kitchen' as const,otherRoom:'',width:120,height:150,quantity:2,structuralType:'Window' as const,openingType:'Sliding' as const};
 const state:FieldState={actor:indoor,projects:[{id:projectId,project_name:'Return visit',project_number:'PRJ-RETURN',structure_readiness:'ready',sales_status:quoted?'quotation_in_progress':'ready_for_quotation',created_by:outdoor.id,registeredBy:outdoor.name,assigned_outdoor_sales_id:outdoor.id,assignedOutdoorSales:outdoor.name,address:'Baghdad',phone:null,created_at:'2026-10-18T08:00:00Z',updated_at:'2026-10-18T08:00:00Z',next_follow_up_at:null,project_notes:null}],openings:[original],queue:[],syncedAt:null,outdoorSales:[outdoor],indoorSales:[indoor]};
 const writes:FieldChange[]=[];
 await page.addInitScript(locale=>localStorage.setItem('alumex_locale',locale),locale);
 await page.route('**/api/**',async route=>{
  if(route.request().method()!=='POST')return route.fulfill({json:state});
  const change=route.request().postDataJSON() as FieldChange;writes.push(change);
  const saved=await savedFieldState(page);state.projects=saved.projects.map(p=>({...p,pending:false}));state.openings=saved.openings;
  return route.fulfill({json:{project:state.projects[0]}});
 });
 await page.goto('/offline?path=/mini-crm');
 const row=page.locator('article').filter({hasText:'Return visit'});
 await row.getByRole('button',{name:locale==='en'?'Add more openings':'إضافة فتحات جديدة',exact:true}).click();
 const form=row.getByRole('form',{name:locale==='en'?'Add more openings':'إضافة فتحات جديدة',exact:true});
 await form.getByRole('combobox',{name:locale==='en'?'Measurements by':'المسؤول عن القياسات',exact:true}).selectOption(outdoor.id);
 await form.getByRole('button',{name:locale==='en'?'Send additional-openings task':'إرسال مهمة إضافة فتحات',exact:true}).click();
 await expect.poll(()=>writes.length).toBe(1);
 await expect.poll(async()=>(await savedFieldState(page)).queue.length).toBe(0);
 expect(writes[0].action).toBe('request-openings');expect(writes[0].userId).toBe(indoor.id);
 expect(state.openings).toEqual([original]);
 state.actor=outdoor;
 await page.goto('/offline?path=/dashboard');
 await expect(page.getByText(locale==='en'?'Add more openings':'إضافة فتحات جديدة',{exact:true})).toBeVisible();
 const nav=page.getByRole('navigation',{name:locale==='en'?'Outdoor Sales workspace':'مساحة عمل المبيعات الخارجية'});
 await expect(nav.getByRole('status')).toHaveText('1');
 await page.getByRole('link',{name:locale==='en'?'Record measurements':'تسجيل القياسات',exact:true}).click();
 const finish=page.getByRole('button',{name:locale==='en'?'Finish measurements — ready for quotation':'إنهاء القياسات — جاهز لعرض السعر',exact:true});
 await finish.click();await expect(page.locator('p[role="alert"]')).toContainText(locale==='en'?'Add at least one new opening':'أضف فتحة جديدة واحدة');
 await expect(page.getByRole('button',{name:locale==='en'?'Edit opening 1':'تعديل الفتحة 1',exact:true})).toHaveCount(0);
 // Save the new group offline, including its repeated quantity, and submit on reconnect.
 await page.evaluate(()=>{Object.defineProperty(navigator,'onLine',{configurable:true,get:()=>false});window.dispatchEvent(new Event('offline'));});
 await page.getByLabel(locale==='en'?'Floor':'الطابق',{exact:true}).selectOption('F1');
 await page.getByRole('combobox',{name:locale==='en'?'Room':'الغرفة',exact:true}).selectOption('Kitchen');
 await page.getByRole('combobox',{name:locale==='en'?'Structural type':'النوع الإنشائي',exact:true}).selectOption('Window');
 await page.getByRole('radio',{name:locale==='en'?'Sliding':'سلايد',exact:true}).check();
 await page.getByRole('radio',{name:locale==='en'?'No arch':'بدون قوس',exact:true}).check();
 await page.getByLabel(locale==='en'?'Width (cm)':'العرض (سم)',{exact:true}).fill('200');
 await page.getByLabel(locale==='en'?'Height (cm)':'الارتفاع (سم)',{exact:true}).fill('220');
 await page.getByRole('button',{name:locale==='en'?'Save & add opening':'حفظ وإضافة فتحة',exact:true}).click();
 await expect.poll(async()=>(await savedFieldState(page)).openings.length).toBe(2);
 await finish.click();
 await page.getByRole('dialog').getByRole('button',{name:locale==='en'?'Submit measurements':'إرسال القياسات',exact:true}).click();
 await expect.poll(async()=>(await savedFieldState(page)).projects[0].additional_openings_state).toBe('submitted');
 expect((await savedFieldState(page)).openings[0]).toEqual(original);
 await expect(nav.getByRole('status')).toHaveCount(0);
 await page.evaluate(()=>{Object.defineProperty(navigator,'onLine',{configurable:true,get:()=>true});window.dispatchEvent(new Event('online'));});
 await expect.poll(async()=>(await savedFieldState(page)).queue.length).toBe(0);
 expect(writes.map(w=>w.action)).toEqual(['request-openings','opening','finish']);
 expect(state.projects[0].sales_status).toBe('ready_for_quotation');
 await page.screenshot({path:test.info().outputPath('additional-openings-submitted.png'),fullPage:true});
});
