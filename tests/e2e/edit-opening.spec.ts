import {expect,test} from '@playwright/test';
import {savedFieldState} from './helpers/fieldState';
import type {FieldChange,FieldState} from '../../src/lib/offline/types';
test.use({serviceWorkers:'block'});
for(const locale of ['en','ar'])for(const online of [true,false])test(`${locale}: edit an opening ${online?'online':'offline'}, cancel a draft, and submit corrected measurements`,async({page})=>{
 const actor={id:'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa',name:'Outdoor employee',role:'Outdoor Sales'};
 const id='11111111-1111-4111-8111-111111111111';
 const opening={id:'bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb',projectId:id,floor:'Ground',room:'Kitchen' as const,otherRoom:'',width:120,height:150,quantity:2,structuralType:'Window' as const,openingType:'Sliding' as const};
 const state:FieldState={actor,projects:[{id,project_name:'Edit measurements sample',project_number:'PRJ-EDIT',created_by:actor.id,registeredBy:actor.name,address:'Baghdad',phone:null,created_at:'2026-10-18T08:00:00Z',updated_at:'2026-10-18T08:00:00Z',structure_readiness:'ready',sales_status:'new_lead',next_follow_up_at:null,project_notes:null}],openings:[opening],queue:[],syncedAt:null,outdoorSales:[],indoorSales:[]};
 const posts:FieldChange[]=[];const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.addInitScript(locale=>localStorage.setItem('alumex_locale',locale),locale);
 await page.route('**/api/**',async route=>{
  if(route.request().method()!=='POST')return route.fulfill({json:state});
  posts.push(route.request().postDataJSON());
  const local=await savedFieldState(page);state.openings=local.openings;state.projects=local.projects;
  return route.fulfill({json:{project:state.projects[0]}});
 });
 await page.goto('/offline?path=/initial-measurements/'+id);
 const editButton=page.getByRole('button',{name:locale==='en'?'Edit opening 1':'تعديل الفتحة ١',exact:true});
 await expect(editButton).toBeVisible();
 if(!online){await page.evaluate(()=>Object.defineProperty(navigator,'onLine',{configurable:true,get:()=>false}));await page.addInitScript(()=>Object.defineProperty(navigator,'onLine',{configurable:true,get:()=>false}));}
 await editButton.click();
 const form=page.getByRole('form',{name:locale==='en'?'Edit opening measurements':'تعديل قياسات الفتحة',exact:true});
 const width=page.getByLabel(locale==='en'?'Width (cm)':'العرض (سم)',{exact:true});
 const height=page.getByLabel(locale==='en'?'Height (cm)':'الارتفاع (سم)',{exact:true});
 const floor=page.getByRole('combobox',{name:locale==='en'?'Floor':'الطابق',exact:true});
 const customFloor=page.getByLabel(locale==='en'?'Specify floor':'حدد الطابق',{exact:true});
 const quantity=page.getByLabel(locale==='en'?'Number of identical openings':'عدد الفتحات المتطابقة',{exact:true});
 await expect(width).toHaveValue('120');await expect(height).toHaveValue('150');await expect(quantity).toHaveValue('2');
 await expect(floor).toHaveValue('Other');await expect(customFloor).toHaveValue('Ground');
 expect(await floor.locator('option').evaluateAll(options=>options.map(o=>(o as HTMLOptionElement).value))).toEqual(['','GF','F1','F2','F3','F4','F5','F6','F7','F8','F9','F10','Roof','Basement','Other']);
 await expect(floor.locator('option[value="Basement"]')).toHaveText(locale==='en'?'Basement':'سرداب');
 await width.fill('190');
 await form.getByRole('button',{name:locale==='en'?'Cancel editing':'إلغاء التعديل',exact:true}).click();
 expect((await savedFieldState(page)).openings[0].width).toBe(120);expect((await savedFieldState(page)).queue).toHaveLength(0);
 await editButton.click();
 await floor.selectOption('F10');await expect(customFloor).toHaveCount(0);
 await width.fill('180');await height.fill('220');await quantity.fill('4');
 const save=form.getByRole('button',{name:locale==='en'?'Save measurement changes':'حفظ تعديلات القياسات',exact:true});
 await save.click();
 await expect.poll(async()=>(await savedFieldState(page)).openings[0].width).toBe(180);
 if(online)await expect.poll(()=>posts.length).toBe(1);
 else expect(posts).toHaveLength(0);
 await page.reload();
 await expect(editButton).toBeVisible();
 expect((await savedFieldState(page)).openings).toHaveLength(1);
 await editButton.click();await expect(width).toHaveValue('180');await expect(height).toHaveValue('220');await expect(quantity).toHaveValue('4');
 await expect(floor).toHaveValue('F10');await floor.selectOption('Other');
 await width.fill('185');await save.click();
 expect((await savedFieldState(page)).openings[0].width).toBe(180);
 await customFloor.fill(locale==='en'?'Mezzanine':'طابق الميزانين');await save.click();
 await expect.poll(async()=>(await savedFieldState(page)).openings[0].width).toBe(185);
 if(online)await expect.poll(()=>posts.length).toBe(2);
 await page.getByRole('button',{name:locale==='en'?'Finish measurements — ready for quotation':'إنهاء القياسات — جاهز لعرض السعر',exact:true}).click();
 await page.getByRole('dialog').getByRole('button',{name:locale==='en'?'Submit measurements':'إرسال القياسات',exact:true}).click();
 await expect(editButton).toHaveCount(0);
 if(!online)await page.evaluate(()=>{Object.defineProperty(navigator,'onLine',{configurable:true,get:()=>true});window.dispatchEvent(new Event('online'));});
 await expect.poll(()=>posts.length).toBe(3);
 await expect.poll(async()=>(await savedFieldState(page)).queue.length).toBe(0);
 expect(posts.map(c=>c.action)).toEqual(['edit-opening','edit-opening','finish']);
 expect(posts[0].payload.previous).toMatchObject({width:120,quantity:2});expect(posts[1].payload.previous).toMatchObject({width:180,quantity:4,floor:'F10'});
 expect(state.openings).toHaveLength(1);expect(state.openings[0]).toMatchObject({id:opening.id,width:185,height:220,quantity:4,floor:locale==='en'?'Mezzanine':'طابق الميزانين'});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);expect(errors).toEqual([]);
});
