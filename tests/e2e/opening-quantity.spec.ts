import {expect,test} from '@playwright/test';
import {savedFieldState} from './helpers/fieldState';
import type {FieldChange,FieldState} from '../../src/lib/offline/types';
test.use({serviceWorkers:'block'});
for(const locale of ['en','ar'])for(const online of [true,false])test(`${locale}: repeated openings save, reload and finish ${online?'online':'offline'}`,async({page})=>{
 const actor={id:'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa',name:'Outdoor employee',role:'Outdoor Sales'};
 const id='11111111-1111-4111-8111-111111111111';
 const state:FieldState={actor,projects:[{id,project_name:'Repeated building windows',project_number:'PRJ-QUANTITY',created_by:actor.id,registeredBy:actor.name,address:'Baghdad',phone:null,created_at:'2026-10-18T08:00:00Z',updated_at:'2026-10-18T08:00:00Z',structure_readiness:'ready',sales_status:'new_lead',next_follow_up_at:null,project_notes:null}],openings:[],queue:[],syncedAt:null,outdoorSales:[],indoorSales:[]};
 const posts:FieldChange[]=[];
 await page.addInitScript(locale=>localStorage.setItem('alumex_locale',locale),locale);
 await page.route('**/api/**',async route=>{
  if(route.request().method()!=='POST')return route.fulfill({json:state});
  const change=route.request().postDataJSON();posts.push(change);
  const local=await savedFieldState(page);state.openings=local.openings;state.projects=local.projects;
  return route.fulfill({json:{project:state.projects[0]}});
 });
 await page.goto('/offline?path=/initial-measurements/'+id);
 const quantity=page.getByLabel(locale==='en'?'Number of identical openings':'عدد الفتحات المتطابقة',{exact:true});
 await expect(quantity).toHaveValue('1');
 if(!online){
  await page.evaluate(()=>{Object.defineProperty(navigator,'onLine',{configurable:true,get:()=>false});window.dispatchEvent(new Event('offline'));});
  await page.addInitScript(()=>Object.defineProperty(navigator,'onLine',{configurable:true,get:()=>false}));
 }
 await page.getByLabel(locale==='en'?'Floor':'الطابق',{exact:true}).selectOption('GF');
 await page.getByRole('combobox',{name:locale==='en'?'Room':'الغرفة',exact:true}).selectOption('Kitchen');
 await page.getByRole('combobox',{name:locale==='en'?'Structural type':'النوع الإنشائي',exact:true}).selectOption('Window');
 await page.getByRole('radio',{name:locale==='en'?'Sliding':'سلايد',exact:true}).check();
 await page.getByLabel(locale==='en'?'Width (cm)':'العرض (سم)',{exact:true}).fill('120');
 await page.getByLabel(locale==='en'?'Height (cm)':'الارتفاع (سم)',{exact:true}).fill('150');
 const save=page.getByRole('button',{name:locale==='en'?'Save & add opening':'حفظ وإضافة فتحة',exact:true});
 await quantity.fill('1.5');await save.click();
 expect((await savedFieldState(page)).openings).toHaveLength(0);
 await quantity.fill('8');await save.click();
 await expect.poll(async()=>(await savedFieldState(page)).openings[0]?.quantity).toBe(8);
 await expect(quantity).toHaveValue('1');
 if(online)await expect.poll(()=>posts.length).toBe(1);
 else expect(posts).toHaveLength(0);
 await page.reload();
 await expect(page.getByRole('table').locator('tbody tr')).toHaveCount(1);
 await expect(page.getByRole('table').locator('tbody tr td').last()).toHaveText(locale==='en'?'8':'٨');
 expect((await savedFieldState(page)).openings[0].quantity).toBe(8);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:test.info().outputPath('repeated-openings.png'),fullPage:true});
 await page.getByRole('button',{name:locale==='en'?'Finish measurements — ready for quotation':'إنهاء القياسات — جاهز لعرض السعر',exact:true}).click();
 await expect.poll(async()=>(await savedFieldState(page)).projects[0].sales_status).toBe('ready_for_quotation');
 if(!online)await page.evaluate(()=>{Object.defineProperty(navigator,'onLine',{configurable:true,get:()=>true});window.dispatchEvent(new Event('online'));});
 await expect.poll(()=>posts.length).toBe(2);
 await expect.poll(async()=>(await savedFieldState(page)).queue.length).toBe(0);
 expect(posts[0].payload.quantity).toBe(8);expect(posts[1].action).toBe('finish');
 expect(state.openings).toHaveLength(1);expect(state.openings[0].quantity).toBe(8);
});
